import assert from "node:assert/strict";
import {placeDoor,overlaps,hitDoor,centerOf,widthOf,closestSide} from "../scripts/room-editor-geometry.mjs";
const cols=22,rows=13;
const north=placeDoor({x:8.27,y:0.31},cols,rows,"door",1,true);
assert.equal(north.side,"N");
assert.equal(north.offset,8.27);
assert.equal(north.width,1);
assert.equal(hitDoor([north],{x:8.27,y:0.32},cols,rows),0);
assert.equal(hitDoor([north],{x:15,y:6},cols,rows),-1);
const moved=placeDoor({x:17.63,y:12.8},cols,rows,"door",.5,true);
assert.equal(moved.side,"S");assert.equal(moved.offset,17.63);assert.equal(moved.width,.5);
const east=placeDoor({x:21.9,y:6.37},cols,rows,"passage",.75,true);
assert.equal(east.side,"E");assert.equal(centerOf(east),6.37);
assert.equal(widthOf(east),.75);
assert.ok(!overlaps([north],east));
assert.ok(overlaps([north],{...north,offset:8.5}));
assert.ok(!overlaps([north],{...north,offset:8.5},0));
const clamped=placeDoor({x:22,y:0.03},cols,rows,"door",2,true);
assert.equal(clamped.side,"E");assert.equal(clamped.offset,1);
const snapped=placeDoor({x:8.17,y:0},cols,rows,"door",1,false);
assert.equal(snapped.offset,8.5);
assert.equal(closestSide({x:11,y:0},cols,rows),"N");
console.log("PASS: free door placement, handle hit testing, width and overlap checks");
