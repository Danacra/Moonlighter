import assert from "node:assert/strict";
import {isOpenPortal,teleportDestination} from "../scripts/portal-core.mjs";
const g=100;
const rooms=[{index:0,x:100,y:100,w:900,h:600},{index:1,x:1000,y:100,w:900,h:600}];
const portal={key:"gate:0",rooms:[0,1],x:1000,y:350,width:g,kind:"door",orientation:"vertical",secret:false};
const open={door:1,ds:1,flags:{"moonlighter-floor-forge":{gateKey:"gate:0"}}};
assert.equal(isOpenPortal(portal,[open]),true);
assert.equal(isOpenPortal(portal,[{...open,ds:0}]),false);
assert.equal(isOpenPortal(portal,[{...open,ds:2}]),false);
assert.equal(isOpenPortal({...portal,secret:true},[{...open,door:2}]),false);
assert.equal(isOpenPortal({...portal,kind:"passage"},[]),true);
assert.equal(isOpenPortal({...portal,kind:"passage",secret:true},[]),false);
const a=teleportDestination(portal,0,rooms,{x:925,y:350},g,1,1);
assert.ok(a&&a.room===1);
assert.ok(a.x>=1000&&a.x<1900);
assert.ok(a.y>=100&&a.y<700);
assert.equal(teleportDestination(portal,0,rooms,{x:200,y:350},g,1,1),null);
assert.equal(teleportDestination(portal,0,rooms,{x:930,y:590},g,1,1),null);
const b=teleportDestination(portal,1,rooms,{x:1080,y:350},g,1,1);
assert.ok(b&&b.room===0&&b.x<1000);
assert.equal(teleportDestination(portal,777,rooms,{x:1000,y:350},g,1,1),null);
const horizontal={key:"gate:1",rooms:[0,2],x:550,y:700,width:120,kind:"door",orientation:"horizontal"};
const three=[...rooms,{index:2,x:100,y:700,w:900,h:700}];
const c=teleportDestination(horizontal,0,three,{x:550,y:610},g,1,1);
assert.ok(c&&c.room===2&&c.y>700);
console.log("PASS: door open/closed state, portal proximity, landing coordinates and two-way movement");
